<script>
(() => {
  // Initialize all .carousel-track sections as carousels
  document.querySelectorAll('.carousel-track').forEach(initCarousel);

  function createEl(tag, cls, html){
    const e = document.createElement(tag);
    if(cls) e.className = cls;
    if(html !== undefined) e.innerHTML = html;
    return e;
  }

  function initCarousel(track){
    // Wrap track in viewport
    const viewport = createEl('div','carousel-viewport');
    track.parentNode.insertBefore(viewport, track);
    viewport.appendChild(track);

    // set inline styles if needed
    track.style.gap = getComputedStyle(track).gap || '24px';
    track.style.alignItems = 'stretch';

    // --- REMOVE ARROWS ---
    // const prev = createEl('button','nav-arrow nav-prev','&#x2039;'); 
    // const next = createEl('button','nav-arrow nav-next','&#x203A;'); 
    // viewport.appendChild(prev); 
    // viewport.appendChild(next);

    // create dots container (hidden, for logic)
    const dotsWrapper = createEl('div','page-dots');
    viewport.parentNode.insertBefore(dotsWrapper, viewport.nextSibling);

    const cards = Array.from(track.children);
    if(!cards.length) return;

    // state
    let page = 0;
    let pages = 1;
    let cardWidth = 0;
    let gap = parseFloat(getComputedStyle(track).gap || 24);

    // measure and build dots
    function recalc(){
      cardWidth = cards[0].getBoundingClientRect().width;
      const viewportWidth = viewport.clientWidth;
      const visible = Math.max(1, Math.floor((viewportWidth + gap) / (cardWidth + gap)));
      pages = Math.max(1, Math.ceil(cards.length / visible));
      if(page >= pages) page = pages - 1;
      buildDots();
      slide();
    }

    function buildDots(){
      dotsWrapper.innerHTML = '';
      for(let i=0;i<pages;i++){
        const d = createEl('button','dot-bullet');
        d.setAttribute('aria-label', 'Go to page ' + (i+1));
        d.addEventListener('click', ()=> { page = i; slide(); });
        dotsWrapper.appendChild(d);
      }
      updateDots();
    }

    function updateDots(){
      Array.from(dotsWrapper.children).forEach((d,i) => d.classList.toggle('active', i===page));
    }

    function slide(){
      const viewportWidth = viewport.clientWidth;
      const visible = Math.max(1, Math.floor((viewportWidth + gap) / (cardWidth + gap)));
      const maxIndex = Math.max(0, cards.length - visible);
      const cardStep = cardWidth + gap;
      const idx = Math.min(maxIndex, page * visible);
      const translate = idx * cardStep;
      track.style.transform = `translateX(-${translate}px)`;
      updateDots();
    }

    // AUTO SLIDE
    let autoSlideInterval;
    function startAutoSlide() {
      autoSlideInterval = setInterval(() => {
        page++;
        if(page >= pages) page = 0;
        slide();
      }, 5000); // 3s per page
    }

    // start after images load
    const imgs = track.querySelectorAll('img');
    const loadPromises = Array.from(imgs).map(img => {
      if(img.complete) return Promise.resolve();
      return new Promise(resolve => img.addEventListener('load', resolve));
    });

    Promise.all(loadPromises).then(() => {
      recalc();
      startAutoSlide();
    });

    window.addEventListener('resize', debounce(recalc, 120));

    function debounce(fn, t){
      let id; 
      return (...a)=>{ 
        clearTimeout(id); 
        id = setTimeout(()=>fn(...a), t); 
      };
    }
  }
})();
</script>



